"""Procedural dishwasher rack tines as a static, primitive-collider text USD asset (issue #47).

Generate (the committed asset is source/kitchenbot/scene/assets/dishwasher/rack_tines.usda; every
default comes from ``kitchenbot.scene.kitchen_dims``, lengths are metres at scale 1.0)::

    py -3.12 scripts/make_rack_tines_usd.py
    py -3.12 scripts/make_rack_tines_usd.py --scale 1.4 --out rack_tines_x1.4.usda

Validate (exit code 1 if anything differs from ``kitchen_dims`` by more than 1 mm or a schema is
missing; pass the same layout flags that wrote the file)::

    py -3.12 scripts/make_rack_tines_usd.py --check <FILE>.usda

Rack frame (the frame of the rack link that #11 attaches this file to): ``x`` across the tines,
``y`` along the two tine rows, ``z`` up, origin at the centre of the underside of the base frame.
The file holds, under the default prim ``/RackTines``:

* ``BaseFrame``: a thin box, rack width by rack depth by base thickness, resting on ``z = 0``;
* ``Tines``: two rows of ``slots + 1`` vertical capsules (a rounded top lets a plate edge slide in)
  standing on the base frame, 12 for 5 slots, rows at ``y = +-row_spacing / 2``;
* ``Slots``: ``Slot_1`` to ``Slot_5``, empty Xforms at the slot poses (gap centre, top of the
  tines, yaw 0), so #11 can read the poses it must match in simulation from the prims;
* ``PhysicsMaterial``: friction 1.0, bound to every collider with the ``physics`` purpose.

Every collider is a primitive (``Cube``, ``Capsule``) with ``UsdPhysics.CollisionAPI``. There is no
``RigidBodyAPI`` anywhere: the tines become part of the rack link in #11, which is the rigid body.
Output is deterministic: the same layout writes byte-identical text.

``scale`` multiplies every length, the pitch and the tine height included (see
``RackSlotLayout``); generate at 1.0 when the file is referenced under a prim that is scaled
already. ``pxr`` (the ``usd-core`` wheel) is imported lazily, so ``--help`` works without it.
Nothing here imports Isaac Sim or Isaac Lab.
"""

import argparse
import math
import sys
from pathlib import Path

from kitchenbot.scene import kitchen_dims as kd
from kitchenbot.scene import usd_prims as up

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = REPO_ROOT / "source/kitchenbot/scene/assets/dishwasher/rack_tines.usda"

ROOT_PATH = "/RackTines"
BASE_PATH = f"{ROOT_PATH}/BaseFrame"
TINES_PATH = f"{ROOT_PATH}/Tines"
SLOTS_PATH = f"{ROOT_PATH}/Slots"
MATERIAL_PATH = f"{ROOT_PATH}/PhysicsMaterial"
ROW_NAMES = ("neg", "pos")  # the tine row at negative y, then the one at positive y
BASE_COLOR = (0.55, 0.55, 0.58)
TINE_COLOR = (0.80, 0.80, 0.83)


def tine_path(row: int, k: int) -> str:
    """Prim path of tine ``k`` (0-based, from the most negative x) in row ``row`` (0 or 1)."""
    return f"{TINES_PATH}/Tine_{ROW_NAMES[row]}_{k + 1}"


def slot_path(i: int) -> str:
    """Prim path of the marker of slot ``i`` (1-based)."""
    return f"{SLOTS_PATH}/Slot_{i}"


def command_line(layout: kd.RackSlotLayout) -> str:
    """The flags that regenerate ``layout`` (written into the file's documentation string)."""
    return (
        f"--slots {layout.slots} --pitch {layout.pitch_m:g} --tine-height "
        f"{layout.tine_height_m:g} --tine-radius {layout.tine_radius_m:g} --row-spacing "
        f"{layout.row_spacing_m:g} --base-thickness {layout.base_thickness_m:g} --rack-width "
        f"{layout.rack_width_m:g} --rack-depth {layout.rack_depth_m:g} --scale {layout.scale:g}"
    )


# --------------------------------------------------------------------------------------------
# Writing (needs usd-core)
# --------------------------------------------------------------------------------------------


def write_rack_tines_usd(layout: kd.RackSlotLayout, out_path) -> Path:
    """Write the tines for ``layout`` to ``out_path`` (text USD when the suffix is ``.usda``)."""
    from pxr import Gf, UsdGeom

    out_path = Path(out_path)
    stage = up.new_stage(
        out_path,
        ROOT_PATH,
        f"Procedural rack tines: {layout.slots} slots, pitch {layout.pitch * 1000:g} mm, "
        f"scale {layout.scale:g}. Rack frame: x across the tines, y along the rows, z up, origin "
        f"at the centre of the base frame underside. Generated by "
        f"scripts/make_rack_tines_usd.py {command_line(layout)}; do not edit by hand.",
    )
    material = up.define_physics_material(
        stage, MATERIAL_PATH, kd.RACK_FRICTION, kd.SURFACE_RESTITUTION
    )

    half_w, half_d = layout.width / 2.0, layout.depth / 2.0
    up.define_box(
        stage,
        BASE_PATH,
        (-half_w, -half_d, 0.0),
        (half_w, half_d, layout.base_thickness),
        material,
        BASE_COLOR,
    )

    UsdGeom.Scope.Define(stage, TINES_PATH)
    z_centre = layout.base_thickness + layout.tine_height / 2.0
    for row, y in enumerate(layout.row_ys):
        for k, x in enumerate(layout.tine_xs):
            up.define_capsule_z(
                stage,
                tine_path(row, k),
                (x, y, z_centre),
                layout.tine_radius,
                layout.tine_height,
                material,
                TINE_COLOR,
            )

    UsdGeom.Scope.Define(stage, SLOTS_PATH)
    for i, (x, y, z, _yaw) in enumerate(layout.slot_poses(), start=1):
        marker = UsdGeom.Xform.Define(stage, slot_path(i))
        marker.AddTranslateOp(UsdGeom.XformOp.PrecisionDouble).Set(
            Gf.Vec3d(up.clean(x), up.clean(y), up.clean(z))
        )

    stage.GetRootLayer().Save()
    return out_path


# --------------------------------------------------------------------------------------------
# Checking (needs usd-core)
# --------------------------------------------------------------------------------------------


def check_rack_tines_usd(path, layout: kd.RackSlotLayout) -> dict:
    """Reopen ``path`` and compare it with ``layout``; ``problems`` empty means it passes."""
    from pxr import Gf, Usd, UsdGeom

    path = Path(path)
    info: dict = {"path": path.as_posix(), "bytes": path.stat().st_size, "problems": []}
    problems: list[str] = info["problems"]
    tol = up.TOLERANCE_M

    stage = Usd.Stage.Open(str(path))
    problems.extend(up.stage_problems(stage))
    root = stage.GetDefaultPrim()
    if not root or str(root.GetPath()) != ROOT_PATH:
        problems.append(f"default prim is {root.GetPath() if root else None}, expected {ROOT_PATH}")
        return info
    problems.extend(up.collider_problems(root, kd.RACK_FRICTION, kd.SURFACE_RESTITUTION))

    colliders = up.collider_prims(root)
    expected_colliders = 1 + 2 * (layout.slots + 1)
    info["colliders"] = len(colliders)
    info["expected_colliders"] = expected_colliders
    if len(colliders) != expected_colliders:
        problems.append(f"{len(colliders)} colliders, expected {expected_colliders}")

    cache = UsdGeom.XformCache()

    def box_of(prim_path: str):
        prim = stage.GetPrimAtPath(prim_path)
        if not prim:
            problems.append(f"missing prim {prim_path}")
            return None
        try:
            return up.world_aabb(prim, cache)
        except ValueError as exc:
            problems.append(str(exc))
            return None

    def expect(label: str, got: float, want: float) -> float:
        error = abs(got - want)
        if error > tol:
            problems.append(
                f"{label} is {got:.4f} m, expected {want:.4f} m (off by {error * 1000:.1f} mm)"
            )
        return error

    base = box_of(BASE_PATH)
    if base is not None:
        lo, hi = base
        info["base_size"] = hi - lo
        for axis, name in enumerate("xyz"):
            want_lo = (-layout.width / 2, -layout.depth / 2, 0.0)[axis]
            want_hi = (layout.width / 2, layout.depth / 2, layout.base_thickness)[axis]
            expect(f"base frame min {name}", lo[axis], want_lo)
            expect(f"base frame max {name}", hi[axis], want_hi)

    # Tines: centre, footprint and height of each, then the gap centres between neighbours.
    tines: list[list[tuple[float, float, float] | None]] = [[], []]  # (x, y, top z) per tine
    for row, row_y in enumerate(layout.row_ys):
        for k, tine_x in enumerate(layout.tine_xs):
            box = box_of(tine_path(row, k))
            if box is None:
                tines[row].append(None)
                continue
            lo, hi = box
            centre = (lo + hi) / 2.0
            label = f"tine {ROW_NAMES[row]}_{k + 1}"
            expect(f"{label} x", centre[0], tine_x)
            expect(f"{label} y", centre[1], row_y)
            expect(f"{label} width x", hi[0] - lo[0], 2.0 * layout.tine_radius)
            expect(f"{label} width y", hi[1] - lo[1], 2.0 * layout.tine_radius)
            expect(f"{label} bottom z", lo[2], layout.base_thickness)
            expect(f"{label} top z", hi[2], layout.slot_entry_z)
            tines[row].append((float(centre[0]), float(centre[1]), float(hi[2])))

    gap_errors: list[float] = []
    gap_centres: list[tuple[float, float, float] | None] = []
    for i in range(1, layout.slots + 1):
        sx, sy, sz, yaw = layout.slot_pose(i)
        # The four tines around slot i: tine i and i + 1 (1-based) of both rows.
        around = [t for row in range(2) for t in tines[row][i - 1 : i + 1]]
        if len(around) != 4 or None in around:
            gap_centres.append(None)
            problems.append(f"slot {i}: a tine next to it is missing")
        else:
            gx = sum(t[0] for t in around) / 4.0  # centre of the four tines = centre of the gap
            gy = sum(t[1] for t in around) / 4.0
            gz = max(t[2] for t in around)
            gap_centres.append((gx, gy, gz))
            gap_errors += [
                expect(f"gap centre of slot {i} (x)", gx, sx),
                expect(f"gap centre of slot {i} (y)", gy, sy),
                expect(f"entry height of slot {i}", gz, sz),
            ]
        marker = stage.GetPrimAtPath(slot_path(i))
        if not marker:
            problems.append(f"missing marker {slot_path(i)}")
            continue
        matrix = cache.GetLocalToWorldTransform(marker)
        direction = matrix.TransformDir(Gf.Vec3d(1.0, 0.0, 0.0))
        marker_yaw = math.atan2(direction[1], direction[0])
        for name, got, want in zip("xyz", matrix.ExtractTranslation(), (sx, sy, sz), strict=True):
            gap_errors.append(expect(f"marker Slot_{i} {name}", got, want))
        if abs(marker_yaw - yaw) > 1e-3:
            problems.append(f"marker Slot_{i} yaw is {marker_yaw:.4f} rad, expected {yaw:.4f}")

    info["gap_centres"] = gap_centres
    info["max_gap_error_m"] = max(gap_errors, default=0.0)
    return info


def format_report(info: dict, layout: kd.RackSlotLayout) -> str:
    """Compact ASCII report for ``--check``."""
    lines = [f"file: {info['path']} ({info['bytes']} bytes)"]
    lines.append(
        f"layout: {layout.slots} slots, pitch {layout.pitch * 1000:g} mm, tine height "
        f"{layout.tine_height * 1000:g} mm, tine radius {layout.tine_radius * 1000:g} mm, rows "
        f"{layout.row_spacing * 1000:g} mm apart, scale {layout.scale:g}"
    )
    if "colliders" in info:
        lines.append(f"colliders: {info['colliders']} (expected {info['expected_colliders']})")
    if "base_size" in info:
        size = info["base_size"]
        lines.append(f"base frame (m): {size[0]:.4f} x {size[1]:.4f} x {size[2]:.4f}")
    if "gap_centres" in info:
        found_and_pose = zip(info["gap_centres"], layout.slot_poses(), strict=True)
        for i, (found, pose) in enumerate(found_and_pose, start=1):
            where = "missing" if found is None else f"x {found[0]:+.4f} y {found[1]:+.4f}"
            lines.append(
                f"slot {i}: gap centre {where}; slot_pose x {pose[0]:+.4f} y {pose[1]:+.4f} "
                f"z {pose[2]:.4f}"
            )
        lines.append(f"max deviation from slot_pose: {info['max_gap_error_m'] * 1000:.3f} mm")
    for problem in info["problems"]:
        lines.append(f"PROBLEM: {problem}")
    lines.append("RESULT: " + ("OK" if not info["problems"] else "FAIL"))
    return "\n".join(lines)


# --------------------------------------------------------------------------------------------
# Command line
# --------------------------------------------------------------------------------------------


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate or check the procedural rack tines USD (issue #47). Lengths are "
        "metres at scale 1.0; --scale multiplies all of them. Defaults: kitchenbot.scene."
        "kitchen_dims.",
    )
    add = parser.add_argument
    d = "(default %(default)s)"
    add("--slots", type=int, default=kd.RACK_SLOTS, help=f"number of slots {d}")
    add("--pitch", type=float, default=kd.RACK_SLOT_PITCH_M, help=f"tine pitch {d}")
    add("--tine-height", type=float, default=kd.RACK_TINE_HEIGHT_M, help=f"above the base {d}")
    add("--tine-radius", type=float, default=kd.RACK_TINE_RADIUS_M, help=f"tine radius {d}")
    add("--row-spacing", type=float, default=kd.RACK_ROW_SPACING_M, help=f"between rows {d}")
    add("--base-thickness", type=float, default=kd.RACK_BASE_THICKNESS_M, help=f"base z {d}")
    add("--rack-width", type=float, default=kd.RACK_WIDTH_M, help=f"base frame x {d}")
    add("--rack-depth", type=float, default=kd.RACK_DEPTH_M, help=f"base frame y {d}")
    add("--scale", type=float, default=kd.RACK_SCALE, help=f"scales every length {d}")
    add("--out", type=Path, default=DEFAULT_OUT, help="output file (default: the committed asset)")
    add(
        "--check",
        type=Path,
        metavar="FILE",
        help="validate FILE against the layout given by the flags instead of writing",
    )
    return parser


def main(argv=None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        layout = kd.RackSlotLayout(
            slots=args.slots,
            pitch_m=args.pitch,
            tine_height_m=args.tine_height,
            tine_radius_m=args.tine_radius,
            row_spacing_m=args.row_spacing,
            base_thickness_m=args.base_thickness,
            rack_width_m=args.rack_width,
            rack_depth_m=args.rack_depth,
            scale=args.scale,
        )
    except ValueError as exc:
        parser.error(str(exc))

    try:
        import pxr  # noqa: F401
    except ImportError:
        print(
            "make_rack_tines_usd.py needs the OpenUSD Python package (module 'pxr').\n"
            "Install it with:  pip install usd-core   (or: pip install -e '.[assets]')",
            file=sys.stderr,
        )
        return 2

    if args.check is not None:
        if not args.check.is_file():
            parser.error(f"no such file: {args.check}")
        info = check_rack_tines_usd(args.check, layout)
        print(format_report(info, layout))
        return 1 if info["problems"] else 0

    path = write_rack_tines_usd(layout, args.out)
    info = check_rack_tines_usd(path, layout)
    print(
        f"wrote {path.as_posix()} ({info['bytes']} bytes): {info['colliders']} colliders, "
        f"max deviation from slot_pose {info['max_gap_error_m'] * 1000:.3f} mm"
    )
    for problem in info["problems"]:
        print(f"PROBLEM: {problem}", file=sys.stderr)
    return 1 if info["problems"] else 0


if __name__ == "__main__":
    sys.exit(main())
