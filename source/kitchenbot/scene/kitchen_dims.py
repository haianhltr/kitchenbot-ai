@dataclass(frozen=True)
class PlateFit:
    """How one plate sits in a slot of a :class:`RackSlotLayout`; all lengths in metres.

    The plate stands vertically in the slot on the base frame, its normal along ``x``, centred
    between the rows.
    """

    diameter: float
    thickness: float
    gap_width: float  # clear distance between two adjacent tines
    side_clearance: float  # free space on each side of the plate in the gap
    depth_margin: float  # (rack depth - diameter) / 2: the plate's widest extent against the depth
    row_margin: float  # rack half-depth minus the outer face of a tine row
    engaged_height: float  # height range of a tine that lies inside the plate's outline
    lean_limit_deg: float | None  # tilt at which the tine tops stop the plate; None if disengaged
    top_z: float  # top of the seated plate in the rack frame
    fits: bool  # the plate is guided by both rows and everything is inside the rack


@dataclass(frozen=True)
class RackSlotLayout:
    """Geometry of the rack tines and the slot poses derived from it.

    The length fields are the values at scale 1.0; ``scale`` multiplies every one of them, so
    every property below (``pitch``, ``slot_entry_z``, ``slot_pose``...) is already scaled and is
    what the generated USD contains. If the tines are referenced under a prim that already carries
    the same scale, generate at ``scale=1.0`` instead. The plates do not scale with the rack: to
    keep a 0.05 m pitch after scaling the asset by ``k``, pass ``pitch_m=0.05 / k`` (and likewise
    for the tine height). #11 owns that decision.

    Slot ``i`` (1-based, ``1 <= i <= slots``) is the gap between tine ``i`` and tine ``i + 1`` of a
    row, centred in ``x``, so slot 3 of 5 is at ``x = 0``. The slot entry is the top of the tines.
    """

    slots: int = RACK_SLOTS
    pitch_m: float = RACK_SLOT_PITCH_M
    tine_height_m: float = RACK_TINE_HEIGHT_M
    tine_radius_m: float = RACK_TINE_RADIUS_M
    row_spacing_m: float = RACK_ROW_SPACING_M
    base_thickness_m: float = RACK_BASE_THICKNESS_M
    rack_width_m: float = RACK_WIDTH_M
    rack_depth_m: float = RACK_DEPTH_M
    scale: float = RACK_SCALE

    def __post_init__(self) -> None:
        if isinstance(self.slots, bool) or not isinstance(self.slots, int) or self.slots < 1:
            raise ValueError(f"slots must be a positive integer, got {self.slots!r}")
        for name in (
            "pitch_m",
            "tine_height_m",
            "tine_radius_m",
            "row_spacing_m",
            "base_thickness_m",
            "rack_width_m",
            "rack_depth_m",
            "scale",
        ):
            value = getattr(self, name)
            if not math.isfinite(value) or value <= 0.0:
                raise ValueError(f"{name} must be positive and finite, got {value!r}")
        if self.pitch_m <= 2.0 * self.tine_radius_m:
            raise ValueError("pitch_m must exceed the tine diameter, or there is no gap")
        if self.slots * self.pitch_m + 2.0 * self.tine_radius_m > self.rack_width_m:
            raise ValueError("the tines do not fit across rack_width_m")
        if self.row_spacing_m + 2.0 * self.tine_radius_m > self.rack_depth_m:
            raise ValueError("the tine rows do not fit inside rack_depth_m")

    # Scaled lengths (metres) ---------------------------------------------------------------

    @property
    def pitch(self) -> float:
        return self.scale * self.pitch_m

    @property
    def tine_height(self) -> float:
        return self.scale * self.tine_height_m

    @property
    def tine_radius(self) -> float:
        return self.scale * self.tine_radius_m

    @property
    def row_spacing(self) -> float:
        return self.scale * self.row_spacing_m

    @property
    def base_thickness(self) -> float:
        return self.scale * self.base_thickness_m

    @property
    def width(self) -> float:
        return self.scale * self.rack_width_m

    @property
    def depth(self) -> float:
        return self.scale * self.rack_depth_m

    @property
    def gap_width(self) -> float:
        """Clear distance between two adjacent tines of a row."""
        return self.pitch - 2.0 * self.tine_radius

    @property
    def slot_entry_z(self) -> float:
        """Top of the tines, the height the planner's ``slot_pose`` means (#43)."""
        return self.base_thickness + self.tine_height

    # Positions in the rack frame -------------------------------------------------------------

    @property
    def tine_xs(self) -> tuple[float, ...]:
        """``x`` of the ``slots + 1`` tines of a row, from the most negative."""
        return tuple((k - self.slots / 2.0) * self.pitch for k in range(self.slots + 1))

    @property
    def row_ys(self) -> tuple[float, float]:
        """``y`` of the two tine rows, negative row first."""
        half = self.row_spacing / 2.0
        return (-half, half)

    def slot_pose(self, i: int) -> tuple[float, float, float, float]:
        """``(x, y, z, yaw)`` of slot ``i`` (1-based) in the rack frame: gap centre, entry height.

        ``yaw`` is 0: the slot frame's ``x`` is the rack's ``x``, across the tines.
        """
        if isinstance(i, bool) or not isinstance(i, int) or not 1 <= i <= self.slots:
            raise ValueError(f"slot index must be an integer in 1..{self.slots}, got {i!r}")
        x = (i - (self.slots + 1) / 2.0) * self.pitch
        return (x, 0.0, self.slot_entry_z, 0.0)

    def slot_poses(self) -> tuple[tuple[float, float, float, float], ...]:
        """:meth:`slot_pose` for slots 1 to ``slots``."""
        return tuple(self.slot_pose(i) for i in range(1, self.slots + 1))

    def plate_fit(self, diameter_m: float, thickness_m: float = PLATE_HEIGHT_M) -> PlateFit:
        """Where a plate of ``diameter_m`` stands in a slot, as numbers (see :class:`PlateFit`).

        A tine row at ``y`` meets the plate's face from the height where the disc is wide enough,
        ``R - sqrt(R^2 - y^2)`` above its lowest point, up to the tine top. The lean limit assumes
        the plate pivots on its lowest point and the tine top is the first thing it touches:
        ``atan(side_clearance / tine_height)``.
        """
        if diameter_m <= 0.0 or thickness_m <= 0.0:
            raise ValueError("diameter_m and thickness_m must be positive")
        radius = diameter_m / 2.0
        row_y = self.row_spacing / 2.0
        if row_y < radius:
            engaged_from = radius - math.sqrt(radius**2 - row_y**2)
            engaged = max(0.0, self.tine_height - engaged_from)
        else:
            engaged = 0.0
        side = (self.gap_width - thickness_m) / 2.0
        depth_margin = (self.depth - diameter_m) / 2.0
        row_margin = self.depth / 2.0 - (row_y + self.tine_radius)
        lean = math.degrees(math.atan2(side, self.tine_height)) if engaged > 0.0 else None
        return PlateFit(
            diameter=diameter_m,
            thickness=thickness_m,
            gap_width=self.gap_width,
            side_clearance=side,
            depth_margin=depth_margin,
            row_margin=row_margin,
            engaged_height=engaged,
            lean_limit_deg=lean,
            top_z=self.base_thickness + diameter_m,
            fits=bool(side > 0.0 and depth_margin >= 0.0 and row_margin >= 0.0 and engaged > 0.0),
        )
