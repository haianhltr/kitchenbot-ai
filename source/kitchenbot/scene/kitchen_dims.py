"""Authored kitchen dimensions: the one place these numbers live (issue #47, no simulator).

The USD generators (``scripts/make_rack_tines_usd.py``, ``scripts/make_counter_usd.py``), their
``--check`` modes, the tests and, later, the scene configs of #10 and #11, the plate spawner and the
planner's slot poses all read this module. Standard library only: nothing here imports ``pxr``,
Isaac Sim, Isaac Lab or torch. Every constant says where it comes from: an issue (``#10`` is the
counter scene, ``#29`` the ArtVIP inspection, ``#30`` the plates), a document section, or
``provisional`` when the value is a placeholder to be measured or tuned in simulation.

Frames
------
Kitchen frame (``counter.usda`` and ``floor.usda`` share it): the origin is on the floor at the
middle of the counter's front edge, ``x`` runs along the counter, ``y`` runs from the front edge
towards the wall (the counter occupies ``0 <= y <= COUNTER_DEPTH_M``), ``z`` is up. The robot
stands ``ROBOT_STANDOFF_M`` in front of the edge, at ``y = -ROBOT_STANDOFF_M``.

Rack frame (:class:`RackSlotLayout`, ``rack_tines.usda``): ``x`` across the tines, ``y`` along the
tine rows, ``z`` up, origin at the centre of the underside of the base frame. This is the planner's
slot frame (``planning/geometry.py``): a seated plate's normal points along ``x``, so a slot pose
has yaw 0 here and the world yaw of a slot is the yaw of the rack link. The rack frame is the
frame of the rack link that #11 attaches the tines to.
"""

